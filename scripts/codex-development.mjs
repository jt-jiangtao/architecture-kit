import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { spawn, execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { join, dirname } from 'node:path'
import { realpathSync } from 'node:fs'
import { mergeManagedConfig, renderConfig, captureCommand } from './lib/codex-development.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const [action, ...args] = process.argv.slice(2)

function run(command, argv, input) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, argv, { cwd: root, stdio: ['pipe', 'pipe', 'pipe'] })
    let stdout = '', stderr = ''
    child.stdout.on('data', chunk => { stdout += chunk })
    child.stderr.on('data', chunk => { stderr += chunk })
    child.on('error', reject)
    child.on('close', (code, signal) => resolve({ stdout, stderr, code, signal }))
    child.stdin.end(input)
  })
}

try {
  if (action === 'configure' || action === 'check') {
    const policy = JSON.parse(await readFile(join(root, 'config/agent-development/policy.json'), 'utf8'))
    const serena = execFileSync('which', ['serena'], { encoding: 'utf8' }).trim()
    const target = join(root, '.codex/config.toml')
    let existing = ''
    try { existing = await readFile(target, 'utf8') } catch (error) { if (error.code !== 'ENOENT') throw error }
    const next = mergeManagedConfig(existing, renderConfig(policy, root, serena))
    const modeTarget = join(root, '.serena/mode.yml')
    const mode = JSON.stringify({ description: 'Expose approved tools despite base-mode exclusions', prompt: '', included_optional_tools: policy.serenaTools }, null, 2) + '\n'
    const contextTarget = join(root, '.serena/context.yml')
    const context = JSON.stringify({ ...policy.serenaContext, fixed_tools: policy.serenaTools }, null, 2) + '\n'
    const projectTarget = join(root, '.serena/project.yml')
    const projectPolicy = { ...policy.serenaProject, fixed_tools: policy.serenaTools }
    const project = '# Generated by pnpm codex:configure; edit config/agent-development/policy.json\n' + JSON.stringify(projectPolicy, null, 2) + '\n'
    if (action === 'check') {
      if (await readFile(modeTarget, 'utf8') !== mode) throw new Error('Serena mode is stale; run pnpm codex:configure')
      if (await readFile(contextTarget, 'utf8') !== context) throw new Error('Serena context is stale; run pnpm codex:configure')
      if (next !== existing) throw new Error('Codex projection is stale; run pnpm codex:configure')
      // Serena rewrites YAML with defaults on activation; compare managed values, not formatting.
      const python = join(dirname(realpathSync(serena)), 'python')
      const actualProject = JSON.parse(execFileSync(python, ['-c', 'import json,sys; from ruamel.yaml import YAML; print(json.dumps(YAML(typ="safe").load(open(sys.argv[1]))))', projectTarget], { encoding: 'utf8' }))
      for (const [key, value] of Object.entries(projectPolicy)) {
        if (JSON.stringify(actualProject[key]) !== JSON.stringify(value)) throw new Error(`Serena setting differs: ${key}; run pnpm codex:configure`)
      }
      const prompt = JSON.parse(execFileSync('codex', ['debug', 'prompt-input', 'check'], { cwd: root, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 }))
      const catalog = prompt.flatMap(message => message.content || []).map(block => block.text || '').join('\n')
      for (const skill of ['brainstorming', 'writing-plans', 'executing-plans']) {
        if (!catalog.includes(`\n- ${skill}:`)) throw new Error(`Superpowers discovery missing: ${skill}`)
      }
      console.log('Serena projections and CLI Superpowers discovery verified')
    } else {
      await mkdir(join(root, '.codex'), { recursive: true })
      await writeFile(target, next)
      await mkdir(join(root, '.serena'), { recursive: true })
      await writeFile(projectTarget, project)
      await writeFile(contextTarget, context)
      await writeFile(modeTarget, mode)
      console.log(`Generated ${target}`)
    }
  } else if (action === 'capture') {
    const argv = args[0] === '--' ? args.slice(1) : args
    if (!argv.length) throw new Error('Usage: pnpm codex:capture -- <command> [args]')
    const directory = join(root, 'artifacts/test-reports/codex-development', `${Date.now()}-${process.pid}`)
    await mkdir(directory, { recursive: true })
    const result = await captureCommand(argv, { run, write: (name, body) => writeFile(join(directory, name), body) })
    console.log(await readFile(join(directory, 'summary.log'), 'utf8'))
    console.log(JSON.stringify({ ...result, directory }))
    process.exitCode = result.code ?? 1
    if (result.compressionCode !== 0) console.error('RTK compression failed; read the raw logs')
  } else throw new Error('Use configure, check, or capture')
} catch (error) {
  console.error(error.message)
  process.exitCode = 1
}
